package com.company.retail.externalapi.security;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

import java.sql.Timestamp;
import java.time.Instant;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * W9-B JDBC 存储单测（H2 PostgreSQL 兼容模式，内存库）：
 * nonce 唯一键防重放 / 惰性清理 / call_logs 留痕 / integration.partners 档案解析。
 */
class JdbcDmzStoresTest {

    private JdbcTemplate jdbc;
    private JdbcNonceStore nonceStore;
    private JdbcCallLogStore callLogStore;
    private JdbcPartnerDirectory directory;

    @BeforeEach
    void setUp() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:dmz_" + System.nanoTime() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
        jdbc = new JdbcTemplate(ds);
        jdbc.execute("CREATE SCHEMA integration");
        jdbc.execute("CREATE TABLE integration.partners ("
                + "partner_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "partner_code VARCHAR(32) NOT NULL UNIQUE, "
                + "type VARCHAR(16), "
                + "status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE', "
                + "scope VARCHAR(4096), "
                + "ip_allowlist VARCHAR(4096))");
        jdbc.execute("CREATE TABLE integration.nonces ("
                + "nonce VARCHAR(64) NOT NULL, "
                + "partner_id BIGINT NOT NULL, "
                + "used_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, "
                + "PRIMARY KEY (nonce, partner_id))");
        jdbc.execute("CREATE TABLE integration.call_logs ("
                + "call_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "partner_id BIGINT, "
                + "direction VARCHAR(8) NOT NULL, "
                + "endpoint VARCHAR(128) NOT NULL, "
                + "http_status INT, "
                + "duration_ms INT, "
                + "result VARCHAR(16), "
                + "trace_id VARCHAR(64), "
                + "created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP)");
        jdbc.update("INSERT INTO integration.partners (partner_code, type, status, scope, ip_allowlist) "
                + "VALUES ('DMS-DEV-01', 'DMS', 'ACTIVE', '[\"echo\", \"submit_application\"]', '127.0.0.1, 10.0.0.0/8')");
        nonceStore = new JdbcNonceStore(jdbc);
        callLogStore = new JdbcCallLogStore(jdbc);
        directory = new JdbcPartnerDirectory(jdbc);
    }

    @Test
    void nonceFirstRecordTrueDuplicateFalse() {
        assertTrue(nonceStore.tryRecord("DMS-DEV-01", "n-1"), "首次登记成功");
        assertFalse(nonceStore.tryRecord("DMS-DEV-01", "n-1"), "同 (nonce, partner) 重放拒绝");
        assertTrue(nonceStore.tryRecord("DMS-DEV-01", "n-2"), "不同 nonce 正常");
        // 不同 partner 不共享 nonce 空间（唯一键按 partner 隔离）
        jdbc.update("INSERT INTO integration.partners (partner_code, type, status) VALUES ('DMS-DEV-02', 'DMS', 'ACTIVE')");
        assertTrue(nonceStore.tryRecord("DMS-DEV-02", "n-1"), "另一 partner 同 nonce 不算重放");
    }

    @Test
    void purgeBeforeDeletesOnlyExpiredNonces() {
        nonceStore.tryRecord("DMS-DEV-01", "n-old");
        jdbc.update("UPDATE integration.nonces SET used_at = ? WHERE nonce = 'n-old'",
                Timestamp.from(Instant.now().minusSeconds(3600)));
        nonceStore.tryRecord("DMS-DEV-01", "n-new");
        int purged = nonceStore.purgeBefore(Instant.now().minusSeconds(600));
        assertEquals(1, purged, "只清留存期外的行");
        Integer remaining = jdbc.queryForObject(
                "SELECT COUNT(*) FROM integration.nonces WHERE nonce = 'n-new'", Integer.class);
        assertEquals(1, remaining, "留存期内不动");
    }

    @Test
    void callLogRecordsWithResolvedPartnerId() {
        callLogStore.record("DMS-DEV-01", "/external/echo", 200, 42, "SUCCESS", "trace-1");
        callLogStore.record("GHOST-PARTNER", "/external/echo", 403, 7, "RF_PTNR_003", "trace-2");
        List<Map<String, Object>> rows = jdbc.queryForList(
                "SELECT partner_id, direction, endpoint, http_status, result, trace_id "
                        + "FROM integration.call_logs ORDER BY call_id");
        assertEquals(2, rows.size());
        assertEquals(1L, ((Number) rows.get(0).get("partner_id")).longValue(), "partner_id 按 code 回查");
        assertEquals("IN", rows.get(0).get("direction"));
        assertEquals(200, ((Number) rows.get(0).get("http_status")).intValue());
        assertEquals("SUCCESS", rows.get(0).get("result"));
        assertNull(rows.get(1).get("partner_id"), "未登记 partner 记 NULL");
        assertEquals("RF_PTNR_003", rows.get(1).get("result"), "失败记语义码");
    }

    @Test
    void directoryParsesScopeArrayAndIpList() {
        PartnerDirectory.PartnerProfile p = directory.profileOf("DMS-DEV-01");
        assertTrue(p.active());
        assertEquals(java.util.Set.of("echo", "submit_application"), p.scopes());
        assertEquals(java.util.List.of("127.0.0.1", "10.0.0.0/8"), p.ipAllowlist());
    }

    @Test
    void directoryTreatsBooleanMapScopeAsTrueKeysAndUnknownPartnerAsNull() {
        jdbc.update("UPDATE integration.partners SET scope = '{\"submit_application\":false,\"echo\":true}' "
                + "WHERE partner_code = 'DMS-DEV-01'");
        assertEquals(java.util.Set.of("echo"), directory.profileOf("DMS-DEV-01").scopes(),
                "布尔图 scope 取 true 键（兼容 V9 种子格式）");
        assertNull(directory.profileOf("NO-SUCH"), "未登记 partner → null");
        jdbc.update("UPDATE integration.partners SET status = 'DISABLED' WHERE partner_code = 'DMS-DEV-01'");
        assertFalse(directory.profileOf("DMS-DEV-01").active(), "DISABLED → active=false");
    }
}
