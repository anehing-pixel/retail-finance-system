# 按长度降序，保证长词先于短词替换
ORDERED = sorted(TERM_MAP.items(), key=lambda kv: -len(kv[0]))


def md_files() -> list[Path]:
    out: list[Path] = []
    for d in DOC_DIRS:
        if not d.is_dir():
            continue
        for p in sorted(d.glob("*.md")):
            out.append(p)
    return out


def normalize_text(text: str) -> tuple[str, int]:
    n = 0
    for old, new in ORDERED:
        if old in text:
            n += text.count(old)
            text = text.replace(old, new)
    # 「反社」单独出现才补全为「反社会势力排查」。
    # 负向先行断言 (?!会) 保证已规范的「反社会势力排查 / 反社会势力排除条款」不再被命中，
    # 因此该规则幂等；不像裸字符串映射那样会自我膨胀或误删正常词。
    text, k = re.subn(r"反社(?!会)", "反社会势力排查", text)
    n += k
    return text, n


def kana_lines(path: Path, text: str) -> list[tuple[int, str]]:
    hits = []
    for i, line in enumerate(text.splitlines(), 1):
        if any(ch in KANA for ch in line):
            hits.append((i, line.strip()[:120]))
    return hits


def main() -> int:
    check_only = "--check" in sys.argv

    # 1) 重命名 ADR 文件
    renamed = 0
    adr_dir = ROOT / "docs" / "adr"
    for old, new in RENAMES.items():
        src, dst = adr_dir / old, adr_dir / new
        if src.exists():
            if dst.exists():
                print(f"[SKIP] 目标已存在，未覆盖：{new}")
                continue
            if check_only:
                print(f"[WOULD RENAME] {old} -> {new}")
                renamed += 1
            else:
                src.rename(dst)
                print(f"[RENAMED] {old} -> {new}")
                renamed += 1

    # 2) 内容替换 + 引用同步
    changed_files = 0
    total_replacements = 0
    residual: list[tuple[str, int, str]] = []
    for p in md_files():
        original = p.read_text(encoding="utf-8")
        normalized, n = normalize_text(original)
        if n and not check_only:
            p.write_text(normalized, encoding="utf-8")
        if n:
            changed_files += 1
            total_replacements += n
        for line_no, line in kana_lines(p, normalized):
            residual.append((p.relative_to(ROOT).as_posix(), line_no, line))

    print("=" * 72)
    print(f"模式            : {'检查（不写盘）' if check_only else '执行规范化'}")
    print(f"扫描 .md 文件   : {len(md_files())}")
    print(f"重命名文件      : {renamed}")
    print(f"内容变更文件    : {changed_files}")
    print(f"术语替换次数    : {total_replacements}")
    print(f"残留假名行数    : {len(residual)}")
    for f, ln, line in residual:
        print(f"  ! {f}:{ln}: {line}")
    print("=" * 72)

    if residual:
        print("FAIL：仍有日文假名残留，需补充术语映射。")
        return 1
    print("PASS：全仓无日文假名残留；文件名与引用已规范化。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
